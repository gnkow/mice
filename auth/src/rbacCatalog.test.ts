describe('RBAC S01 permission catalog', () => {
  it('matches the authorization-system spec catalog tables', () => {
    assert.deepEqual([...INSTANCE_PERMISSION_CATALOG], [...SPEC_CATALOG])
  })

  it('accepts catalog members and rejects unknown or legacy permission strings', () => {
    assert.equal(isInstancePermission('repo:bypass_acl'), true)
    assert.equal(isInstancePermission('namespace:create'), true)
    assert.equal(isInstancePermission('create_namespace'), false)
    assert.equal(isInstancePermission('view_audit'), false)
    assert.equal(isInstancePermission(''), false)
  })
})
