const SPEC_BUNDLES: Record<InstanceRole, readonly string[]> = {
  external: EXTERNAL,
  user: USER,
  manager: MANAGER,
  auditor: AUDITOR,
  admin: ADMIN,
}

describe('RBAC S02 role permission bundles', () => {
  it('maps each formal role to its spec permission set', () => {
    for (const role of Object.keys(SPEC_BUNDLES) as InstanceRole[]) {
      assert.deepEqual(getRolePermissions(role), [...SPEC_BUNDLES[role]], role)
    }
  })

  it('enforces separation of duties for Admin and Auditor', () => {
    const admin = new Set(getRolePermissions('admin'))
    const auditor = new Set(getRolePermissions('auditor'))
    assert.equal(admin.has('audit:read'), false)
    assert.equal(admin.has('repo:files:read'), false)
    assert.equal(admin.has('repo:bypass_acl'), false)
    assert.equal(auditor.has('repo:bypass_acl'), true)
    assert.equal(auditor.has('audit:read'), true)
    assert.equal(auditor.has('instance:admins:add'), false)
  })
})
